export function stationToTrack(station: RadioStation): Track {
  return {
    id: `radio-${station.id}`,
    title: station.name,
    artist: station.tagline,
    album: `${station.frequency} • ${station.location}`,
    genre: station.genre,
    duration: 0, // Live infinite stream
    type: 'radio',
    audioUrl: station.streamUrl,
    coverArt: station.coverArt,
    radioStationId: station.id,
    frequency: station.frequency,
    frequencyVal: station.frequencyVal,
    bitrate: station.bitrate,
    isLiveRadio: true,
  };
}
